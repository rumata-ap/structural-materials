class Masonry:
    """Расчетные характеристики неармированной кладки."""

    def __init__(
        self,
        stone_type: str,
        stone_grade: str,
        mortar_grade: str,
        mortar_type: str = "cement_lime",
        area_m2: float = 1.0,
        is_ground_wet: bool = False,
        long_term_hardening: bool = False,
        specimen_grinded: bool = False,
        stone_hollow_percent: float = 0.0,
        experimental_R: Optional[float] = None,
        **kwargs: Any,
    ) -> None:
        self.stone_type = _canonical_stone_type(stone_type)
        self.stone_grade = (
            str(stone_grade).strip()
            if self.stone_type == "aerated_concrete"
            else _grade_label(stone_grade)
        )
        self.mortar_grade = (
            str(mortar_grade).strip()
            if str(mortar_grade).strip().lower() in {"glue", "клей", "клеевой"}
            else _grade_label(mortar_grade, default_prefix="B")
            if self.stone_type == "rubble_concrete" and str(mortar_grade).strip().upper().startswith(("B", "В"))
            else _grade_label(mortar_grade)
        )
        self.mortar_type = str(mortar_type).strip().lower().replace("-", "_")
        self.area_m2 = float(area_m2)
        self.is_ground_wet = bool(is_ground_wet)
        self.long_term_hardening = bool(long_term_hardening)
        self.specimen_grinded = bool(specimen_grinded)
        self.stone_hollow_percent = float(stone_hollow_percent)
        self.experimental_R = None if experimental_R is None else float(experimental_R)
        self.options = dict(kwargs)
        if self.area_m2 <= 0:
            raise ValueError("area_m2 должен быть положительным")
        if not 0 <= self.stone_hollow_percent <= 100:
            raise ValueError("stone_hollow_percent должен быть в диапазоне 0..100")
        if self.experimental_R is not None and self.experimental_R < 0:
            raise ValueError("experimental_R не может быть отрицательным")
        if self._is_glue and self.experimental_R is None:
            raise ValueError(
                "Для кладки на клею требуется experimental_R по сноске 1 к таблице 6.3"
            )

    @property
    def _is_glue(self) -> bool:
        return self.mortar_type in {"glue", "клей", "adhesive"} or self.mortar_grade.lower() in {
            "glue",
            "клей",
            "клеевой",
        }

    @property
    def _mortar_mark(self) -> Optional[float]:
        return _mortar_mark(self.mortar_grade)

    @property
    def R_base(self) -> float:
        if self.experimental_R is not None:
            return self.experimental_R
        if self.stone_type == "brick":
            value = _lookup(TABLE_6_1_BRICK, self.stone_grade, self.mortar_grade)
            hollow = self.stone_hollow_percent
            if 28 <= hollow <= 42:
                value *= 0.8
            elif 43 <= hollow <= 48:
                mark = self._mortar_mark or 0.0
                value *= 0.75 if mark >= 100 else 0.70 if mark >= 50 else 0.65 if mark >= 10 else 0.60
        elif self.stone_type == "ceramic_large_block":
            joint = str(self.options.get("vertical_joint", "")).lower().replace("-", "_")
            if joint in {"tongue_groove", "паз_гребень", "паз_гребень"}:
                grade = _grade_number(self.stone_grade)
                if grade == 75:
                    value = 0.9
                elif grade == 50:
                    value = 0.7
                else:
                    raise ValueError("Для паз-гребня нормативно заданы только М75 и М50")
            else:
                try:
                    value = _lookup(
                        TABLE_6_2_CERAMIC_LARGE_BLOCKS,
                        self.stone_grade,
                        self.mortar_grade,
                    )
                except ValueError:
                    if self._mortar_mark is None or self._mortar_mark >= 50:
                        raise
                    value = _lookup(TABLE_6_2_CERAMIC_LARGE_BLOCKS, self.stone_grade, "M100")
                if self._mortar_mark is not None and self._mortar_mark < 50:
                    value *= 0.8
        elif self.stone_type == "aerated_concrete":
            if self._is_glue:
                return self.experimental_R  # validated in __init__
            value = _lookup(TABLE_6_3_AERATED_MORTAR, self.stone_grade, self.mortar_grade)
            if (
                not bool(self.options.get("is_autoclaved", True))
                or self.mortar_type in {"light", "легкий"}
                or 15 <= float(self.options.get("joint_thickness_mm", 0)) <= 20
            ):
                value *= 0.9
        elif self.stone_type == "concrete_large_block":
            concrete_grade = _grade_label(
                self.options.get("concrete_grade", self.stone_grade),
                default_prefix="B",
            )
            block_grade = _grade_label(
                self.options.get("block_grade", self.stone_grade)
            )
            try:
                value = TABLE_6_4_CONCRETE_LARGE_BLOCKS[concrete_grade][block_grade][
                    _grade_label(self.mortar_grade)
                ]
            except KeyError as exc:
                raise ValueError("Нет комбинации в таблице 6.4") from exc
            if value is None:
                raise ValueError("Комбинация в таблице 6.4 отсутствует")
        elif self.stone_type == "concrete_solid_stone":
            value = _lookup(TABLE_6_5_CONCRETE_SOLID_STONES, self.stone_grade, self.mortar_grade)
        elif self.stone_type == "concrete_hollow_stone":
            value = _lookup(TABLE_6_6_CONCRETE_HOLLOW_STONES, self.stone_grade, self.mortar_grade)
            if self.stone_hollow_percent > 25:
                mark = self._mortar_mark or 0
                value *= 0.8 if mark >= 50 else 0.7 if mark >= 25 else 0.6
        elif self.stone_type == "vibro_brick":
            value = _lookup(TABLE_6_7_VIBRO_BRICK, self.stone_grade, self.mortar_grade)
            if self.options.get("is_vibrated", False):
                value *= 1.05
            thickness = self.options.get("brick_thickness_mm")
            if thickness is not None and float(thickness) == 88:
                value *= 1.1
            if float(self.options.get("wall_thickness_cm", 0)) > 30:
                value *= 0.85
            width = float(self.options.get("wall_width_cm", 40))
            if 25 <= width <= 38:
                value *= 0.8
        elif self.stone_type == "natural_stone":
            height = float(self.options.get("row_height_mm", 150))
            section = "up_to_150" if height <= 150 else "200_300"
            value = _lookup(TABLE_6_8_NATURAL_STONES[section], self.stone_grade, self.mortar_grade)
        elif self.stone_type == "rubble_stone":
            value = _lookup(TABLE_6_9_RUBBLE_STONE, self.stone_grade, self.mortar_grade)
            age_days = self.options.get("rubble_age_days")
            if age_days is not None and float(age_days) <= 28 and (self._mortar_mark or 0) >= 4:
                value *= 0.8
            if str(self.options.get("rubble_type", "")).lower() in {"bedded", "постелистый"}:
                value *= 1.5
            context = str(self.options.get("trench_backfill", "")).lower()
            if context in {"trench", "враспор", "superstructure", "надстройка"}:
                value += 0.2
            elif context in {"backfill", "pazukha", "пазуха"}:
                value += 0.1
        elif self.stone_type == "rubble_concrete":
            stone_mark = _grade_number(self.stone_grade) or 0
            stone_key = "M200+" if stone_mark >= 200 else "M100" if stone_mark >= 100 else "M50"
            concrete_grade = _grade_label(self.mortar_grade, default_prefix="B")
            value = TABLE_6_10_RUBBLE_CONCRETE[stone_key].get(concrete_grade)
            if value is None:
                raise ValueError("Нет комбинации в таблице 6.10")
            if self.options.get("is_vibrated", False):
                value *= 1.15
        else:
            raise AssertionError(f"Неподдерживаемый тип {self.stone_type}")
        return float(value) * self._mortar_modifier

    @property
    def _mortar_modifier(self) -> float:
        mark = self._mortar_mark
        if mark is None or not 4 <= mark <= 50:
            return 1.0
        mortar_type = self.mortar_type
        if mortar_type in {"rigid_cement", "cement", "жесткий_цементный", "жесткий цементный"}:
            return 0.85
        if mortar_type in {"organic_plasticizer", "organic", "пластификатор"}:
            return 0.90
        if mortar_type in {"light", "light_mortar", "легкий", "lime_young"}:
            return 0.85
        return 1.0

    @property
    def gamma_c(self) -> float:
        gamma = 1.0
        if self.area_m2 <= 0.3:
            gamma *= 0.8
        if self.is_ground_wet:
            gamma *= 0.8
        if self.long_term_hardening:
            gamma *= 1.15
        if self.specimen_grinded:
            gamma *= 0.9
        if self.stone_hollow_percent > 48:
            gamma *= 0.8
        if self.options.get("horizontal_voids", False):
            gamma *= 0.6
        if self.options.get("is_circular_unreinforced", False):
            gamma *= 0.6
        if self.mortar_type in {"potash", "поташ"}:
            gamma *= 0.85
        if self.options.get("material_gamma_c") is not None:
            gamma *= float(self.options["material_gamma_c"])
        return gamma

    @property
    def R(self) -> float:
        return self.R_base * self.gamma_c

    @property
    def _k_coeff(self) -> float:
        if self.stone_type == "aerated_concrete":
            return TABLE_6_15_K_COEFF["aerated"]
        if self.stone_hollow_percent > 57:
            return TABLE_6_15_K_COEFF["hollow_gt_57"]
        return TABLE_6_15_K_COEFF["standard"]

    @property
    def Ru(self) -> float:
        return self._k_coeff * self.R

    @property
    def alpha(self) -> float:
        mark = self._mortar_mark
        if self.stone_type == "brick":
            family = "brick_silicate" if self.options.get("brick_material") == "silicate" else "brick_plastic"
        elif self.stone_type == "ceramic_large_block":
            family = "ceramic_stones"
        elif self.stone_type == "aerated_concrete":
            family = (
                "aerated_autoclaved_blocks"
                if bool(self.options.get("is_autoclaved", True))
                else "aerated_nonautoclaved_blocks"
            )
        elif self.stone_type in {"rubble_stone", "natural_stone", "concrete_solid_stone"}:
            family = "heavy_stones_and_rubble"
        elif self.stone_type == "rubble_concrete":
            return 2000.0
        else:
            family = "large_heavy_blocks"
        if mark is None or mark >= 25:
            category = "M25+"
        elif mark >= 10:
            category = "M10"
        elif mark >= 4:
            category = "M4"
        elif mark > 0:
            category = "M0.2"
        else:
            category = "M0"
        return TABLE_6_16_ALPHA[family][category] * (
            0.7 if self.mortar_type in {"light", "light_mortar", "легкий"} else 1.0
        )

    @property
    def E0(self) -> float:
        return self.alpha * self.Ru

    @property
    def E_strength(self) -> float:
        return 0.5 * self.E0

    @property
    def E_stiffness(self) -> float:
        return 0.8 * self.E0

    def _joint_value(self, property_name: str) -> float:
        category = _mortar_strength_category(self.mortar_grade)
        values = TABLE_6_11_TENSION_JOINTS[property_name]["unbonded"]
        value = values[category]
        if self.stone_hollow_percent > 0 or self.stone_type == "concrete_hollow_stone":
            value *= 1.25
        if self.mortar_type in {"rigid_cement", "cement", "жесткий_цементный", "жесткий цементный"}:
            value *= 0.75
        if self.options.get("brick_material") == "silicate":
            value *= 0.7
        return value

    @property
    def Rt_joint(self) -> float:
        return self._joint_value("Rt")

    @property
    def Rtb_joint(self) -> float:
        return self._joint_value("Rtb")

    @property
    def Rsq_joint(self) -> float:
        return self._joint_value("Rsq")

    @property
    def _stone_tension_grade(self) -> str:
        grade = _grade_label(self.stone_grade)
        if grade not in TABLE_6_12_TENSION_STONES:
            raise ValueError(f"Марка {self.stone_grade!r} отсутствует в таблице 6.12")
        return grade

    @property
    def Rt_stone(self) -> float:
        return float(TABLE_6_12_TENSION_STONES[self._stone_tension_grade]["Rt"])

    @property
    def Rtb_stone(self) -> float:
        return float(TABLE_6_12_TENSION_STONES[self._stone_tension_grade]["Rtb"])

    @property
    def Rsq_stone(self) -> float:
        return float(TABLE_6_12_TENSION_STONES[self._stone_tension_grade]["Rsq"])

    @property
    def Rtw_stone(self) -> float:
        return self.Rtb_stone

    def get_diagram(self, n_points: int = 100) -> Tuple[np.ndarray, np.ndarray]:
        if n_points < 2:
            raise ValueError("n_points должен быть не менее 2")
        eps_0 = 1.1 * self.Ru / self.E0
        strain = np.linspace(0.0, 8.0 * eps_0, int(n_points))
        stress = self.Ru * (1.0 - np.exp(-strain / eps_0))
        return strain, stress

    def with_mesh_reinforcement(
        self,
        wire_diameter_mm: float,
        mesh_step_c_mm: float,
        mesh_rows_spacing: int,
        row_height_mm: float,
        rebar_class: str = "B500",
        Rs: float = 415.0,
        brick_type: str = "single",
        experimental_R: Optional[float] = None,
        **kwargs: Any,
    ) -> "ReinforcedMasonry":
        return ReinforcedMasonry(
            masonry=self,
            wire_diameter_mm=wire_diameter_mm,
            mesh_step_c_mm=mesh_step_c_mm,
            mesh_rows_spacing=mesh_rows_spacing,
            row_height_mm=row_height_mm,
            rebar_class=rebar_class,
            Rs=Rs,
            brick_type=brick_type,
            experimental_R=experimental_R,
            **kwargs,
        )

    def to_dict(self) -> Dict[str, Any]:
        return {
            "stone_type": self.stone_type,
            "stone_grade": self.stone_grade,
            "mortar_grade": self.mortar_grade,
            "mortar_type": self.mortar_type,
            "area_m2": self.area_m2,
            "stone_hollow_percent": self.stone_hollow_percent,
            "R_base": self.R_base,
            "gamma_c": self.gamma_c,
            "R": self.R,
            "Ru": self.Ru,
            "alpha": self.alpha,
            "E0": self.E0,
            "E_strength": self.E_strength,
            "E_stiffness": self.E_stiffness,
        }

    def to_markdown(self) -> str:
        return (
            "| Параметр | Значение | Ед. |\n"
            "|---|---:|---|\n"
            f"| Тип кладки | {self.stone_type} | — |\n"
            f"| Камень | {self.stone_grade} | — |\n"
            f"| Раствор | {self.mortar_grade} | — |\n"
            f"| R | {self.R:.4g} | МПа |\n"
            f"| Ru | {self.Ru:.4g} | МПа |\n"
            f"| E0 | {self.E0:.4g} | МПа |"
        )


class ReinforcedMasonry:
    """Сетчатое армирование по п. 7.31 СП 15.13330.2020."""

    def __init__(
        self,
        masonry: Masonry,
        wire_diameter_mm: float,
        mesh_step_c_mm: float,
        mesh_rows_spacing: int,
        row_height_mm: float,
        rebar_class: str = "B500",
        Rs: float = 415.0,
        brick_type: str = "single",
        experimental_R: Optional[float] = None,
        wire_intersections: bool = True,
        **kwargs: Any,
    ) -> None:
        self.masonry = masonry
        self.wire_diameter_mm = float(wire_diameter_mm)
        self.mesh_step_c_mm = float(mesh_step_c_mm)
        self.mesh_rows_spacing = int(mesh_rows_spacing)
        self.row_height_mm = float(row_height_mm)
        self.rebar_class = _canonical_rebar_class(rebar_class)
        self.Rs = float(Rs)
        self.brick_type = str(brick_type).strip().lower().replace("-", "_")
        self.experimental_R = (
            masonry.experimental_R if experimental_R is None else float(experimental_R)
        )
        self.wire_intersections = bool(wire_intersections)
        self.options = dict(kwargs)
        self.invalid_reasons: List[str] = []
        self._validate_inputs()

    def _validate_inputs(self) -> None:
        if self.mesh_step_c_mm < 30 or self.mesh_step_c_mm > 120:
            self.invalid_reasons.append("размер ячейки c должен быть в диапазоне 30..120 мм")
        if self.mesh_rows_spacing < 1:
            self.invalid_reasons.append("шаг сеток в рядах должен быть положительным")
        if self.row_height_mm <= 0:
            self.invalid_reasons.append("высота ряда должна быть положительной")
        max_diameter = 6.0 if self.wire_intersections else 8.0
        if self.wire_diameter_mm < 3.0 or self.wire_diameter_mm > max_diameter:
            self.invalid_reasons.append(
                f"диаметр проволоки должен быть в диапазоне 3..{max_diameter:g} мм"
            )
        if self.masonry.stone_type not in {"brick", "ceramic_large_block"}:
            self.invalid_reasons.append("формула 7.23 применима к кирпичу и керамическим камням")
        stone_grade = _grade_number(self.masonry.stone_grade)
        minimum_stone_grade = 75.0 if self.masonry.stone_type == "brick" else 35.0
        if stone_grade is None or stone_grade < minimum_stone_grade:
            self.invalid_reasons.append(
                f"марка камня должна быть не ниже М{minimum_stone_grade:g}"
            )
        mortar_mark = self.masonry._mortar_mark
        if mortar_mark is None or mortar_mark < 50:
            self.invalid_reasons.append("марка раствора для армокаменных элементов должна быть не ниже М50")
        if self.row_height_mm > 150:
            self.invalid_reasons.append("высота ряда более 150 мм: нужна экспериментальная R")
        max_mu = 1.0 if self.rebar_class in {"A240", "A300"} else 0.75
        if self.mu > max_mu + 1e-12:
            self.invalid_reasons.append(
                f"процент армирования mu не должен превышать {max_mu:g}%"
            )
        if self.mesh_rows_spacing > self._max_rows:
            self._constructive_by_spacing = True
        else:
            self._constructive_by_spacing = False
        if self.masonry.stone_type == "natural_stone" or self.brick_type == "stone":
            if self.row_height_mm > 140 or self.mesh_rows_spacing * self.row_height_mm > 450:
                self._constructive_by_spacing = True

    @property
    def fs_mm2(self) -> float:
        return math.pi * self.wire_diameter_mm**2 / 4.0

    @property
    def s_mm(self) -> float:
        return self.mesh_rows_spacing * self.row_height_mm

    @property
    def mu(self) -> float:
        if self.mesh_step_c_mm <= 0 or self.s_mm <= 0:
            return 0.0
        return 2.0 * self.fs_mm2 / (self.mesh_step_c_mm * self.s_mm) * 100.0

    @property
    def p_coeff(self) -> float:
        hollow = self.masonry.stone_hollow_percent
        if hollow <= 20:
            return 2.0
        if hollow <= 30:
            return 1.5
        return 1.0

    @property
    def gamma_cs(self) -> Optional[float]:
        if self.rebar_class == "A240":
            return TABLE_6_14_GAMMA_CS["mesh"]["A240"]
        if self.rebar_class == "A300":
            return TABLE_6_14_GAMMA_CS["mesh"]["A300"]
        return TABLE_6_14_GAMMA_CS["mesh"]["B500"]

    @property
    def _max_rows(self) -> int:
        if self.brick_type == "single":
            return 5
        if self.brick_type == "thickened":
            return 4
        if self.brick_type == "stone":
            return 3
        return 5

    @property
    def is_constructive_only(self) -> bool:
        return bool(self._constructive_by_spacing)

    @property
    def is_applicable(self) -> bool:
        return not self.invalid_reasons

    @property
    def Rsk(self) -> Optional[float]:
        if not self.is_applicable:
            return self.experimental_R
        if self.is_constructive_only or self.mu < 0.1:
            return self.masonry.R
        gamma_cs = self.gamma_cs
        if gamma_cs is None:
            return None
        increased = self.masonry.R + self.p_coeff * self.mu * self.Rs * gamma_cs / 100.0
        return min(increased, 2.0 * self.masonry.R)

    @property
    def alpha_sk(self) -> Optional[float]:
        return None if self.Rsk is None else self.masonry.alpha

    @property
    def E0_sk(self) -> Optional[float]:
        if self.Rsk is None:
            return None
        return self.masonry.alpha * self.Rsk * self.masonry._k_coeff

    def to_markdown(self) -> str:
        rsk = "н/д" if self.Rsk is None else f"{self.Rsk:.4g}"
        status = "применимо" if self.is_applicable else "неприменимо: " + "; ".join(self.invalid_reasons)
        return (
            self.masonry.to_markdown()
            + "\n\n"
            + "| Армирование | Значение | Ед. |\n"
            + "|---|---:|---|\n"
            + f"| Диаметр проволоки | {self.wire_diameter_mm:g} | мм |\n"
            + f"| Шаг сеток | {self.s_mm:g} | мм |\n"
            + f"| mu | {self.mu:.4g} | % |\n"
            + f"| Rsk | {rsk} | МПа |\n"
            + f"| Статус | {status} | — |"
        )


def generate_masonry_code_snippet(
    masonry: Masonry,
    reinforced_masonry: Optional[ReinforcedMasonry] = None,
) -> str:
    """Генерирует переносимый фрагмент Python-кода для расчетного блокнота."""
    lines = [
        "from sp15_materials import Masonry",
        "",
        "masonry = Masonry(",
        f"    stone_type={masonry.stone_type!r},",
        f"    stone_grade={masonry.stone_grade!r},",
        f"    mortar_grade={masonry.mortar_grade!r},",
        f"    mortar_type={masonry.mortar_type!r},",
        f"    area_m2={masonry.area_m2!r},",
        f"    stone_hollow_percent={masonry.stone_hollow_percent!r},",
        ")",
        "",
        "print(f'R = {masonry.R:.4g} MPa, E0 = {masonry.E0:.4g} MPa')",
    ]
    if reinforced_masonry is not None:
        lines[0] = "from sp15_materials import Masonry"
        lines.extend(
            [
                "",
                "reinforced = masonry.with_mesh_reinforcement(",
                f"    wire_diameter_mm={reinforced_masonry.wire_diameter_mm!r},",
                f"    mesh_step_c_mm={reinforced_masonry.mesh_step_c_mm!r},",
                f"    mesh_rows_spacing={reinforced_masonry.mesh_rows_spacing!r},",
                f"    row_height_mm={reinforced_masonry.row_height_mm!r},",
                f"    rebar_class={reinforced_masonry.rebar_class!r},",
                f"    Rs={reinforced_masonry.Rs!r},",
                f"    brick_type={reinforced_masonry.brick_type!r},",
                ")",
                "print(f'Rsk = {reinforced.Rsk:.4g} MPa')",
            ]
        )
    return "\n".join(lines)


