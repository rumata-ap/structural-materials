    if canonical == "concrete_large_block":
        values = set()
        for rows in TABLE_6_4_CONCRETE_LARGE_BLOCKS.values():
            values.update(rows)
        return sorted(values, key=lambda item: _grade_number(item) or 0, reverse=True)
