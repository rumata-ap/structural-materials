def _as_number(value: Any) -> Optional[float]:
    if value is None:
        return None
    if isinstance(value, (int, float)):
        return float(value)
    text = str(value).strip().replace(",", ".")
    if text in {"", "-", "—"}:
        return None
    try:
        return float(text)
    except ValueError:
        return None


def _grade_label(value: Any, *, default_prefix: str = "M") -> str:
    text = str(value).strip().replace(",", ".")
    text = text.replace("М", "M").replace("м", "M")
    text = text.replace("В", "B").replace("в", "B")
    if text.lower() in {"нулевой", "zero", "none"}:
        return "M0"
    if text.startswith(("M", "B")):
        prefix, body = text[0], text[1:]
    else:
        prefix, body = default_prefix, text
    number = _as_number(body)
    if number is None:
        return text
    if number.is_integer():
        body = str(int(number))
    else:
        body = f"{number:g}"
    return f"{prefix}{body}"


def _grade_number(value: Any) -> Optional[float]:
    label = _grade_label(value)
    body = label[1:] if label[:1] in {"M", "B"} else label
    return _as_number(body)


def _source_rows(index: int) -> List[List[str]]:
    return _SOURCE_TABLES[index]["rows"]


def _mortar_header_labels(row: List[str]) -> List[str]:
    labels: List[str] = []
    for index, item in enumerate(row):
        if _as_number(item) is None and index == len(row) - 1:
            labels.append("M0")
        else:
            labels.append(_grade_label(item, default_prefix="M"))
    return labels


def _matrix_table(
    rows: List[List[str]],
    mortar_row: int,
    data_start: int,
    *,
    grade_col: int = 0,
    value_start: int = 1,
    mortar_value_start: int = 0,
    default_prefix: str = "M",
) -> Dict[str, Dict[str, Optional[float]]]:
    mortar_grades = _mortar_header_labels(rows[mortar_row][mortar_value_start:])
    table: Dict[str, Dict[str, Optional[float]]] = {}
    for row in rows[data_start:]:
        if len(row) <= grade_col or _grade_number(row[grade_col]) is None:
            break
        grade = _grade_label(row[grade_col], default_prefix=default_prefix)
        table[grade] = {
            mortar: _as_number(row[value_start + index])
            if value_start + index < len(row)
            else None
            for index, mortar in enumerate(mortar_grades)
        }
    return table


