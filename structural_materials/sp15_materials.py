def _canonical_stone_type(value: str) -> str:
    key = str(value).strip().lower().replace("-", "_")
    if key not in _STONE_TYPE_ALIASES:
        raise ValueError(
            f"Неизвестный stone_type={value!r}; доступно: {list_masonry_stone_types()}"
        )
    return _STONE_TYPE_ALIASES[key]


def _canonical_rebar_class(value: str) -> str:
    text = str(value).strip().upper().replace("В", "B")
    if text in {"BP500", "BP-1", "BP1", "BP500-1"}:
        return "B500"
    if text.startswith("B"):
        return "B500"
    if text.startswith("A240"):
        return "A240"
    if text.startswith("A300"):
        return "A300"
    return text


def _mortar_mark(value: Any) -> Optional[float]:
    if value is None:
        return None
    if str(value).strip().lower() in {"glue", "клей", "клеевой"}:
        return None
    label = _grade_label(value)
    return _grade_number(label)


def _mortar_strength_category(value: Any) -> str:
    mark = _mortar_mark(value)
    if mark is None:
        return "M0.2"
    if mark >= 50:
        return "M50+"
    if mark >= 25:
        return "M25"
    if mark >= 10:
        return "M10"
    if mark >= 4:
        return "M4"
    return "M0.2"


def _lookup(table: Dict[str, Dict[str, Optional[float]]], grade: str, mortar: str) -> float:
    grade_key = _grade_label(grade)
    mortar_key = _grade_label(mortar)
    try:
        value = table[grade_key][mortar_key]
    except KeyError as exc:
        raise ValueError(
            f"Нет нормативного значения для stone_grade={grade!r}, mortar_grade={mortar!r}"
        ) from exc
    if value is None:
        raise ValueError(
            f"Комбинация stone_grade={grade!r}, mortar_grade={mortar!r} отсутствует в таблице"
        )
    return float(value)


